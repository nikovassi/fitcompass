function macrosFor(ingredients, servings) {
  const t = { kcal: 0, protein: 0, carbs: 0, fat: 0, fiber: 0 };
  for (const [id, g] of ingredients) {
    const f = getFood(id);
    if (!f) throw new Error(`Липсва храна ${id}`);
    for (const k of Object.keys(t)) t[k] += ((f.per100[k] ?? 0) * g) / 100;
  }
  for (const k of Object.keys(t)) t[k] /= servings;
  return t;
}

